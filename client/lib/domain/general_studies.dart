  static List<GeneralStudies> get all {
    if (_all.isEmpty) {
      GeneralStudies? generalStudies;
      for (final line in checklist().split('\n')) {
        if (!line.startsWith('- ')) {
          if (generalStudies != null) {
            _all.add(generalStudies);
          }
          generalStudies = GeneralStudies(line);
        } else {
          generalStudies!.courses.add(line.substring(2));
        }
      }
      _all.add(generalStudies!);
    }
    return _all;
  }

